
# for loop, iterating over a string 

print ("List Iteration")

l = ["geeks", "for", "geeks"]

for i in l:
    print (i)
 

# for loop, iterating over a Tuple 

print ("\nTuple Iteration")

t = ["geeks", "for", "geeks"]

for i in t:
    print (i)
 
# for loop, iterating over a String 

print ("\nString Iteration")

s = ["Geeks"]

for i in s:
    print (i)
 
